#!/usr/bin/env python3
"""Generates the factory presets of every plugin, the same in all formats, from tools/presets/.

tools/presets/<plugin>.json holds a list of [preset name, {slider name: value}]: names and
values are checked against the plugin's .jsfx header like the FX chains (tools/build_chains.py),
enum sliders take their option label and anything not given keeps the plugin's default. Every
plugin also gets a first preset, "Default", with the default values. Written from that:
  DATA/Effects/null_jsfx/<plugin>.jsfx.rpl         REAPER preset library of the JSFX
  DATA/Effects/null_jsfx/gfx/<plugin>_gfx.jsfx.rpl the same for the GFX version
  DATA/Effects/null_jsfx/gfx/<plugin>_gfx.jsfx     its preset selector: a generated block at the
                                                   end of @init and a call at the end of @gfx
  native/plugins/<plugin>/FactoryPresets.hpp       the list the VST3/CLAP interface offers
File sliders (Convolution's IR File) are left out everywhere: a preset keeps the chosen file.

With --ini <dir> it also writes the same presets as REAPER user preset files, <dir>/js-*.ini,
which REAPER reads from the presets folder of its resource path without importing anything.
The release packages and the installers carry those (not checked in).

Usage: build_presets.py              write them
       build_presets.py --check      exit 1 if any of them is out of date (used by CI)
       build_presets.py --validate   only check tools/presets/*.json, write nothing
       build_presets.py --ini <dir>  write the REAPER user preset files (js-*.ini) into <dir>
"""
import base64
import json
import re
import struct
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ in tools/
sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_chains import fmt, parse_sliders, resolve  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
PLUGINS = ROOT / "DATA/Effects/null_jsfx"
NATIVE = ROOT / "native/plugins"
SOURCE = ROOT / "tools/presets"
MAX_PRESETS = 16
MAX_NAME = 24


GFX_BEGIN = "  // ---- factory presets: generated by tools/build_presets.py, do not edit ----"
GFX_END = "  // ---- end of factory presets ----"
GFX_CALL = "  ng_presets(); // the preset list (generated by tools/build_presets.py)"


def file_sliders(stem):
    """Indices (from 0) of the file sliders (slider:/folder:default:Name) of a plugin."""
    text = (PLUGINS / f"{stem}.jsfx").read_text(encoding="utf-8")
    return {int(m.group(1)) - 1 for m in re.finditer(r"^slider(\d+):/", text, re.M)}


def steps(stem):
    """{index from 0: step} of the sliders that declare a step."""
    text = (PLUGINS / f"{stem}.jsfx").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r"^slider(\d+):[^<\n]*<([^>]*)>", text, re.M):
        parts = m.group(2).split("{")[0].split(":")[0].split(",")
        if len(parts) >= 3 and parts[2].strip():
            out[int(m.group(1)) - 1] = (float(parts[0]), float(parts[2]))
    return out


def load(stem):
    """[(name, [value per slider])] for a plugin: Default first, then tools/presets/<stem>.json."""
    sliders = parse_sliders(PLUGINS / f"{stem}.jsfx")
    defaults = [s[1] for s in sliders]
    out = [("Default", defaults)]
    path = SOURCE / f"{stem}.json"
    if path.exists():
        for name, values in json.loads(path.read_text(encoding="utf-8")):
            if not name or len(name) > MAX_NAME or '"' in name or "`" in name or name in [n for n, _ in out]:
                sys.exit(f"build_presets: {stem}: bad or repeated preset name {name!r} (max {MAX_NAME} chars)")
            vals = list(defaults)
            grid = steps(stem)
            for i, v, key in resolve(f"preset {name!r}", stem, values):
                if i in grid and grid[i][1] > 0:
                    k = (v - grid[i][0]) / grid[i][1]
                    if abs(k - round(k)) > 1e-6:
                        sys.exit(f"build_presets: {stem}: preset {name!r}: {key} = {v} is not on the slider's step {fmt(grid[i][1])}")
                vals[i] = v
            out.append((name, vals))
    if len(out) > MAX_PRESETS:
        sys.exit(f"build_presets: {stem}: more than {MAX_PRESETS} presets")
    return out


def rpl(desc, presets, files):
    """A REAPER preset library: per preset, base64 of the JS state as REAPER stores it (the 64
    slider values, '-' for unused or kept, the quoted preset name, a 0 byte and the wet level 1.0)."""
    lines = [f"<REAPER_PRESET_LIBRARY `JS: {desc}`"]
    for name, vals in presets:
        cells = ["-" if i in files else fmt(v) for i, v in enumerate(vals)]
        text = " ".join(cells + ["-"] * (64 - len(vals))) + f' "{name}"'
        b64 = base64.b64encode(text.encode() + b"\0" + struct.pack("<f", 1.0)).decode()
        lines.append(f"  <PRESET `{name}`")
        lines += [f"    {b64[i:i + 128]}" for i in range(0, len(b64), 128)]
        lines.append("  >")
    return "\n".join(lines + [">", ""])


def ini_name(effect):
    """REAPER's user preset file for a JSFX, from its path under Effects: slashes and dots become
    underscores (null_jsfx/gfx/delay_gfx.jsfx -> js-null_jsfx_gfx_delay_gfx_jsfx.ini)."""
    return "js-" + re.sub(r"[/\\.]", "_", effect) + ".ini"


def ini(presets, files):
    """REAPER user presets: per preset the JS state as text (64 slider values, '-' for unused or
    kept, the name, quoted when it has a space), stored as hex with a checksum byte (sum of the
    bytes) and its length without that byte."""
    lines = ["[General]", f"NbPresets={len(presets)}", ""]
    for i, (name, vals) in enumerate(presets):
        cells = ["-" if j in files else fmt(v) for j, v in enumerate(vals)]
        quoted = f'"{name}"' if " " in name else name
        data = (" ".join(cells + ["-"] * (64 - len(vals))) + " " + quoted).encode()
        lines += [f"[Preset{i}]", f"Data={(data + bytes([sum(data) % 256])).hex().upper()}",
                  f"Len={len(data)}", f"Name={name}", ""]
    return "\n".join(lines) + "\n"


def write_ini(out):
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for path in sorted(PLUGINS.glob("*.jsfx")):
        stem, presets, skip = path.stem, load(path.stem), file_sliders(path.stem)
        targets = [f"null_jsfx/{stem}.jsfx"]
        if (PLUGINS / "gfx" / f"{stem}_gfx.jsfx").exists():
            targets.append(f"null_jsfx/gfx/{stem}_gfx.jsfx")
        for effect in targets:
            (out / ini_name(effect)).write_bytes(ini(presets, skip).encode())
            n += 1
    print(f"build_presets: wrote {n} preset files to {out}")


def cfloat(v):
    return (str(int(v)) + ".0f") if float(v) == int(v) else repr(round(float(v), 6)) + "f"


def header(stem, presets, files):
    """The C++ list: per preset its name and the value of every parameter (the sliders without
    the file sliders, in order)."""
    n = len(presets[0][1]) - len(files)
    rows = "\n".join("    { " + json.dumps(name) + ", { "
                     + ", ".join(cfloat(v) for i, v in enumerate(vals) if i not in files) + " } },"
                     for name, vals in presets)
    return f"""// generated by tools/build_presets.py from tools/presets/{stem}.json - do not edit
// SPDX-License-Identifier: MIT
#pragma once

#include <cstdint>

namespace nullpresets {{

struct FactoryPreset {{
    const char* name;
    float values[{n}];
}};

static const FactoryPreset kPresets[] = {{
{rows}
}};
static constexpr uint32_t kNumPresets = sizeof(kPresets) / sizeof(kPresets[0]);
static constexpr uint32_t kNumValues = {n};

}} // namespace nullpresets
"""


def gfx_block(stem, presets, files):
    """EEL2 for the end of @init of <stem>_gfx.jsfx: the functions the header's preset selector
    (null_gfx.jsfx-inc) calls through ng_presets()."""
    idx = [i for i in range(len(presets[0][1])) if i not in files]
    out = [GFX_BEGIN, f"  ng_pre_n = {len(presets)};", "",
           "  function ng_preset_load(p)", "  ("]
    for k, (_, vals) in enumerate(presets):
        out.append(f"    p == {k} ? ( " + " ".join(f"ng_slider_set({i + 1}, {fmt(vals[i])});" for i in idx) + " );")
    out += ["  );", "", "  // the first preset every slider matches, or -1", "  function ng_preset_match() local(m)", "  (", "    m = -1;"]
    for k, (_, vals) in enumerate(presets):
        out.append(f"    m < 0 && " + " && ".join(f"ng_pre_eq(slider{i + 1}, {fmt(vals[i])})" for i in idx) + f" ? m = {k};")
    out += ["    m;", "  );", "", "  function ng_preset_name(p) local(s)", "  (", '    s = "";']
    for k, (name, _) in enumerate(presets):
        out.append(f'    p == {k} ? s = "{name}";')
    out += ["    s;", "  );", "",
            "  function ng_presets() local(i)", "  (",
            "    ng_pre_req >= 0 ? ( ng_preset_load(ng_pre_req); update(); ng_pre_req = -1; );",
            "    ng_pre_cur = ng_preset_match();",
            "    ng_pre_open ? (",
            "      ng_pre_menu_begin();",
            "      i = 0;",
            "      loop(ng_pre_n, ng_pre_item(i, ng_preset_name(i)); i += 1;);",
            "      ng_pre_menu_end();",
            "    );",
            '    strcpy(#ng_pre_name, ng_pre_cur >= 0 ? ng_preset_name(ng_pre_cur) : "CUSTOM");',
            "  );", GFX_END]
    return out


def gfx_source(path, block):
    """<stem>_gfx.jsfx with the generated block at the end of @init and the call at the end of
    @gfx (any earlier copy of either replaced)."""
    lines = path.read_text(encoding="utf-8").split("\n")
    for first, last in ((GFX_BEGIN, GFX_END), (GFX_CALL, GFX_CALL)):
        if first in lines:
            a, b = lines.index(first), lines.index(last)
            del lines[a - 1:b + 1]  # with the blank line put before it
    # the block goes after the last code line of @init
    init = lines.index("@init")
    nxt = next(i for i in range(init + 1, len(lines)) if lines[i].startswith("@"))
    end = nxt
    while end > init + 1 and not lines[end - 1].strip():
        end -= 1
    lines[end:end] = [""] + block
    # the call after the last code line of @gfx (the last section of every GFX plugin)
    gfx = max(i for i, l in enumerate(lines) if l.startswith("@gfx"))
    end = len(lines)
    while end > gfx + 1 and not lines[end - 1].strip():
        end -= 1
    lines[end:end] = ["", GFX_CALL]
    return "\n".join(lines).rstrip("\n") + "\n"


def render():
    files = {}
    stems = sorted(p.stem for p in PLUGINS.glob("*.jsfx"))
    for f in SOURCE.glob("*.json"):
        if f.stem not in stems:
            sys.exit(f"build_presets: {f.name}: there is no {f.stem}.jsfx")
    for stem in stems:
        presets = load(stem)
        skip = file_sliders(stem)
        desc = (PLUGINS / f"{stem}.jsfx").read_text(encoding="utf-8").split("\n", 1)[0][len("desc:"):].strip()
        files[PLUGINS / f"{stem}.jsfx.rpl"] = rpl(desc, presets, skip)
        gfx = PLUGINS / "gfx" / f"{stem}_gfx.jsfx"
        if gfx.exists():
            gdesc = gfx.read_text(encoding="utf-8").split("\n", 1)[0][len("desc:"):].strip()
            files[PLUGINS / "gfx" / f"{stem}_gfx.jsfx.rpl"] = rpl(gdesc, presets, skip)
            files[gfx] = gfx_source(gfx, gfx_block(stem, presets, skip))
        if (NATIVE / stem / "Plugin.cpp").exists():
            files[NATIVE / stem / "FactoryPresets.hpp"] = header(stem, presets, skip)
    return files


def main():
    if "--ini" in sys.argv:
        write_ini(Path(sys.argv[sys.argv.index("--ini") + 1]))
        return
    files = render()
    if "--validate" in sys.argv:
        for p in sorted(SOURCE.glob("*.json")):
            print(f"{p.stem}: {', '.join(n for n, _ in load(p.stem)[1:])}")
        return
    if "--check" in sys.argv:
        stale = [p for p, t in files.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            sys.exit("build_presets: out of date (run tools/build_presets.py): "
                     + " ".join(str(p.relative_to(ROOT)) for p in stale))
        n = sum(len(load(p.stem)) - 1 for p in PLUGINS.glob("*.jsfx"))
        print(f"build_presets: up to date ({n} presets)")
        return
    for p, t in files.items():
        if not p.exists() or p.read_text(encoding="utf-8") != t:
            p.write_text(t, encoding="utf-8", newline="\n")
    print(f"build_presets: wrote presets for {len(files)} files")


if __name__ == "__main__":
    main()
