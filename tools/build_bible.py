#!/usr/bin/env python3
"""Generates Part III (the plugin registry) of NULL_JSFX_BIBLE.md from the plugin files.

Everything between <!-- BEGIN REGISTRY --> and <!-- END REGISTRY --> is rewritten: the totals,
the exceptions (released CLAP ids that differ from the file name, plugins without a Rack module)
and one table per category with each plugin's name, file, site slug, DISTRHO unique id, Rack
module, GFX size and slider count. All of it is read from the files, so the Bible can never drift:
  DATA/Effects/null_jsfx/<file>.jsfx            name (line 1), category (line 4), sliders
  DATA/Effects/null_jsfx/gfx/<file>_gfx.jsfx    the @gfx size (also the VST3/CLAP UI size)
  native/plugins/<file>/DistrhoPluginInfo.h     unique id, CLAP id
  native/plugins/rack/modules/<file>.hpp        Rack module
  DATA/FXChains, tools/presets, RackPresets.hpp the chain, preset and Rack preset counts

Usage: build_bible.py           rewrite the registry
       build_bible.py --check   exit 1 if it is out of date (used by CI)
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIBLE = ROOT / "NULL_JSFX_BIBLE.md"
PLUGINS = ROOT / "DATA/Effects/null_jsfx"
NATIVE = ROOT / "native/plugins"
CATEGORIES = ("One Slider", "Essentials", "Advanced", "Instruments", "MIDI")
BEGIN = "<!-- BEGIN REGISTRY: generated by tools/build_bible.py -->"
END = "<!-- END REGISTRY -->"


def plugins():
    out = []
    for path in sorted(PLUGINS.glob("*.jsfx")):
        stem = path.stem
        lines = path.read_text(encoding="utf-8").split("\n")
        gfx = (PLUGINS / "gfx" / f"{stem}_gfx.jsfx").read_text(encoding="utf-8")
        size = re.search(r"^@gfx\s+(\d+)\s+(\d+)", gfx, re.M)
        info = (NATIVE / stem / "DistrhoPluginInfo.h").read_text(encoding="utf-8")
        out.append({
            "name": lines[0][len("desc:NULL "):],
            "stem": stem,
            "category": lines[3].split(": ", 1)[1],
            "sliders": sum(1 for l in lines if re.match(r"slider\d+:", l)),
            "gfx": f"{size.group(1)}x{size.group(2)}",
            "uid": re.search(r"DISTRHO_PLUGIN_UNIQUE_ID\s+(\S+)", info).group(1),
            "clap": re.search(r'DISTRHO_PLUGIN_CLAP_ID\s+"([^"]+)"', info).group(1),
            "rack": (NATIVE / "rack/modules" / f"{stem}.hpp").exists(),
        })
    return out


def registry():
    ps = plugins()
    by_cat = {c: sorted((p for p in ps if p["category"] == c), key=lambda p: p["name"].lower()) for c in CATEGORIES}
    chains = len(list((ROOT / "DATA/FXChains/NULL JSFX").glob("*.RfxChain")))
    gfx_chains = len(list((ROOT / "DATA/FXChains/NULL JSFX GFX").glob("*.RfxChain")))
    presets = sum(len(json.loads(f.read_text(encoding="utf-8"))) for f in (ROOT / "tools/presets").glob("*.json"))
    rack = (NATIVE / "rack/RackPresets.hpp").read_text(encoding="utf-8")
    table = rack[rack.index("kPresets[] = {"):]
    rack_presets = len(re.findall(r'^\s*\{ "', table[:table.index("};")], re.M))
    counts = ", ".join(f"{len(by_cat[c])} {c}" for c in CATEGORIES)
    clap = [p for p in ps if p["clap"] != f"tech.nulljsfx.{p['stem']}"]
    no_rack = [p for p in ps if not p["rack"]]
    out = [BEGIN, "", "**Totals:**",
           f"- {len(ps)} plugins: {counts}.",
           f"- {sum(p['rack'] for p in ps)} Rack modules.",
           f"- {chains} FX chains in `NULL JSFX` and {gfx_chains} in `NULL JSFX GFX`.",
           f"- {presets:,} factory presets, Default included.",
           f"- {rack_presets} Rack presets, Init included.",
           "",
           "**Exceptions:**",
           "- **CLAP ids that differ from the file name** (released, frozen by R3): "
           + ", ".join(f"`{p['clap']}`" for p in clap) + ".",
           "- **No Rack module** (R13): " + ", ".join(p["name"] for p in no_rack) + ".",
           ""]
    for c in CATEGORIES:
        out += [f"### {c} ({len(by_cat[c])})", "",
                "| Plugin | File | Site slug | Unique ID | Rack | GFX | Sliders |",
                "|---|---|---|---|---|---|---|"]
        out += [f"| {p['name']} | `{p['stem']}` | `{p['stem'].replace('_', '-')}` | `{p['uid']}` | "
                f"{'yes' if p['rack'] else 'no'} | {p['gfx']} | {p['sliders']} |" for p in by_cat[c]]
        out.append("")
    out.append(END)
    return "\n".join(out)


def main(check):
    text = BIBLE.read_text(encoding="utf-8")
    start, end = text.index(BEGIN), text.index(END) + len(END)
    new = text[:start] + registry() + text[end:]
    if new == text:
        print("build_bible: up to date")
        return 0
    if check:
        print("build_bible: NULL_JSFX_BIBLE.md Part III is out of date; run tools/build_bible.py")
        return 1
    BIBLE.write_text(new, encoding="utf-8")
    print("build_bible: Part III rewritten")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
